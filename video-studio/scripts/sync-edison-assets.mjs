#!/usr/bin/env node
// sync-edison-assets.mjs — scans public/edison for real images and emits a manifest
// Set so KenBurnsImage can fall back to a procedural <ProceduralPlate> when an asset
// is missing. Renders therefore never break on a 404.
//
// After adding real photos to public/edison, re-run `npm run edison:manifest`:
// those shots will switch from procedural plates back to the real <Img>.

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PUBLIC = path.join(__dirname, "..", "public", "edison");
const OUT = path.join(__dirname, "..", "src", "data", "edison-asset-manifest.ts");

const EXTS = new Set([".jpg", ".jpeg", ".png", ".webp"]);
const found = [];

function walk(dir) {
  if (!fs.existsSync(dir)) return;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(full);
    } else if (EXTS.has(path.extname(entry.name).toLowerCase())) {
      found.push(path.relative(PUBLIC, full).split(path.sep).join("/"));
    }
  }
}

walk(PUBLIC);

const body = `// AUTO-GENERATED by scripts/sync-edison-assets.mjs — do not edit by hand.
// Lists every image present in public/edison. KenBurnsImage renders a procedural
// <ProceduralPlate> for any shot whose src is NOT in this set, so renders never
// break on a missing asset. Re-run \`npm run edison:manifest\` after adding images.
export const EDISON_ASSETS = new Set<string>(${JSON.stringify(found, null, 2)});
`;

fs.writeFileSync(OUT, body);

console.log(`edison-asset-manifest: ${found.length} asset(s) -> ${path.relative(process.cwd(), OUT)}`);
for (const f of found) console.log("  ", f);
if (!found.length) console.log("  (none — all KenBurns shots render procedural plates)");
